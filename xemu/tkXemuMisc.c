/*
 *----------------------------------------------------------------------
 *
 * Tk_SetCaretPos --
 *
 *	Record the position of the insertion cursor, for input methods.
 *
 * Results:
 *	None.
 *
 * Side effects:
 *	The position is stored in the display, for input methods.
 *
 *----------------------------------------------------------------------
 */

void
Tk_SetCaretPos(
    Tk_Window tkwin,
    int x, int y,
    int height)
{
    TkWindow *winPtr = (TkWindow *)tkwin;
    TkDisplay *dispPtr = winPtr->dispPtr;

    dispPtr->caret.winPtr = winPtr;
    dispPtr->caret.x = x;
    dispPtr->caret.y = y;
    dispPtr->caret.height = height;
}

/*
 *----------------------------------------------------------------------
 *
 * TkpGetEventTime --
 *
 *	The time of an event generated by Tk. The times of the events of the
 *	ports (Wayland compositors) are those of the monotonic clock.
 *
 * Results:
 *	The current time of the monotonic clock, in milliseconds.
 *
 * Side effects:
 *	None.
 *
 *----------------------------------------------------------------------
 */

unsigned long
TkpGetEventTime(void)
{
    struct timespec ts;

    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (unsigned long)(ts.tv_sec * 1000UL + ts.tv_nsec / 1000000UL);
}

