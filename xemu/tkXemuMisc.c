/*
 *----------------------------------------------------------------------
 *
 * Tk_SetCaretPos --
 *
 *	Record the position of the insertion cursor, for input methods and
 *	the on-screen keyboard.
 *
 * Results:
 *	None.
 *
 * Side effects:
 *	The position is stored in the display, and given to the text input
 *	(Wayland) and to the on-screen keyboard if the window has the focus.
 *
 *----------------------------------------------------------------------
 */

void
Tk_SetCaretPos(
    Tk_Window tkwin,
    int x, int y,
    int height)
{
    TkWindow *winPtr = (TkWindow *)tkwin;
    TkDisplay *dispPtr = winPtr->dispPtr;

    TkKeyboardSetCaret(winPtr);
    dispPtr->caret.winPtr = winPtr;
    dispPtr->caret.x = x;
    dispPtr->caret.y = y;
    dispPtr->caret.height = height;
#ifdef TK_USE_WAYLAND
    TkWlTextInputSetCaret(winPtr, x, y, height);
#endif
}

/*
 *----------------------------------------------------------------------
 *
 * TkpGetEventTime --
 *
 *	The time of an event generated by Tk. The times of the events of the
 *	ports (Wayland compositors, Android) are those of the monotonic
 *	clock.
 *
 * Results:
 *	The current time of the monotonic clock, in milliseconds.
 *
 * Side effects:
 *	None.
 *
 *----------------------------------------------------------------------
 */

unsigned long
TkpGetEventTime(void)
{
    struct timespec ts;

    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (unsigned long)(ts.tv_sec * 1000UL + ts.tv_nsec / 1000000UL);
}

